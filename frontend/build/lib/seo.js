/**
 * SEO & HOSTING FILES
 *
 * PURPOSE:
 * Generates files that search engines and hosting providers read:
 * - sitemap.xml     list of all public pages
 * - robots.txt      rules for search engine crawlers
 * - _headers        security headers (Netlify / Cloudflare Pages)
 * - site.webmanifest
 * - structured data (JSON-LD) for the <head> of each page
 *
 * All URLs are built from siteConfig.url, so changing the domain
 * only requires changing ONE value in /frontend/config/site.js.
 */

import { escapeHtml } from "./html.js";

export function absoluteUrl(site, pathname = "/") {
    return `${site.url}${pathname.startsWith("/") ? pathname : `/${pathname}`}`;
}

export function createSitemap(site, pages) {
    const today = new Date().toISOString().slice(0, 10);
    const entries = pages
        .filter((page) => !page.noindex)
        .map((page) => `  <url>\n    <loc>${escapeHtml(absoluteUrl(site, page.path))}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`)
        .join("\n");
    return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

export function createRobots(site) {
    return [
        "# robots.txt – generated by /frontend/build/lib/seo.js",
        "User-agent: *",
        "Allow: /",
        "Disallow: /demos/",
        "",
        `Sitemap: ${absoluteUrl(site, "/sitemap.xml")}`,
        ""
    ].join("\n");
}

/**
 * Content Security Policy for the static website.
 * Only files from our own domain are allowed. No inline scripts,
 * no third-party trackers. If the backend runs on another domain
 * (site.apiOrigin), it is allowed for form submissions.
 */
export function createContentSecurityPolicy(site) {
    const connect = ["'self'", site.apiOrigin].filter(Boolean).join(" ");
    return [
        "default-src 'self'",
        "script-src 'self'",
        "style-src 'self'",
        "img-src 'self' data:",
        "font-src 'self'",
        `connect-src ${connect}`,
        "frame-src 'self'",
        "frame-ancestors 'self'",
        "form-action 'self'",
        "base-uri 'self'",
        "object-src 'none'",
        "upgrade-insecure-requests"
    ].join("; ");
}

export function createHeadersFile(site) {
    return [
        "# Security headers for static hosting (Netlify / Cloudflare Pages).",
        "# Generated by /frontend/build/lib/seo.js – edit there, not here.",
        "/*",
        `  Content-Security-Policy: ${createContentSecurityPolicy(site)}`,
        "  X-Content-Type-Options: nosniff",
        "  X-Frame-Options: SAMEORIGIN",
        "  Referrer-Policy: strict-origin-when-cross-origin",
        "  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()",
        "  Cross-Origin-Opener-Policy: same-origin",
        "  Strict-Transport-Security: max-age=31536000; includeSubDomains",
        "",
        "/assets/*",
        "  Cache-Control: public, max-age=31536000, immutable",
        "",
        "/media/*",
        "  Cache-Control: public, max-age=604800",
        "",
        "/demos/*",
        "  X-Robots-Tag: noindex",
        ""
    ].join("\n");
}

export function createManifest(site) {
    return JSON.stringify(
        {
            name: site.name,
            short_name: site.name,
            description: site.description,
            start_url: "/",
            display: "standalone",
            background_color: "#090A09",
            theme_color: "#090A09",
            icons: [
                { src: "/favicon.svg", sizes: "any", type: "image/svg+xml" },
                { src: "/assets/brand/icon-192.png", sizes: "192x192", type: "image/png" },
                { src: "/assets/brand/icon-512.png", sizes: "512x512", type: "image/png" }
            ]
        },
        null,
        2
    );
}

/**
 * Structured data (schema.org). Helps search engines understand
 * who the site is about. Returns a <script type="application/ld+json">.
 * (JSON-LD is data, not code, so it is allowed by the CSP.)
 */
export function createStructuredData(site, page) {
    const sameAs = site.social.map((profile) => profile.url).filter(Boolean);
    const person = {
        "@type": "Person",
        "@id": `${site.url}/#person`,
        name: site.name,
        url: site.url,
        jobTitle: site.jobTitle,
        knowsAbout: site.knowsAbout,
        image: absoluteUrl(site, "/assets/images/portrait/lukas-ude-portrait.jpg"),
        ...(sameAs.length ? { sameAs } : {})
    };

    const graph = [
        person,
        { "@type": "WebSite", "@id": `${site.url}/#website`, url: site.url, name: site.name, inLanguage: site.language, publisher: { "@id": `${site.url}/#person` } },
        { "@type": "WebPage", url: absoluteUrl(site, page.path), name: page.fullTitle, description: page.description, isPartOf: { "@id": `${site.url}/#website` } }
    ];

    if (page.breadcrumbs?.length) {
        graph.push({
            "@type": "BreadcrumbList",
            itemListElement: page.breadcrumbs.map((crumb, index) => ({
                "@type": "ListItem",
                position: index + 1,
                name: crumb.label,
                item: absoluteUrl(site, crumb.href)
            }))
        });
    }

    // "<" is escaped so content can never close the script tag early.
    const json = JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2).replace(/</g, "\\u003c");
    return `<script type="application/ld+json">\n${json}\n</script>`;
}
